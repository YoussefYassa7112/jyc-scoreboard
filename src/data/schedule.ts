export type ScheduleGroup = "all" | "red" | "green";
export type ScheduleSection = "morning" | "midday" | "evening" | "full";

export type ScheduleBlock = {
  id: string;
  title: string;
  /** Clock range, single time, or "TBD" */
  time?: string;
  /** Display name for the one place this block happens */
  location?: string;
  /** Single key into src/data/locations.ts — one event, one place */
  locationIds?: string[];
  note?: string;
  group: ScheduleGroup;
  section: ScheduleSection;
  /** Optional absolute times — used by the live-camp simulation preview */
  startMs?: number;
  endMs?: number;
  /** When set, only these cabin numbers follow this parallel block. */
  cabinIds?: number[];
  details?: string[];
};

export type CampDay = {
  id: string;
  label: string;
  dateLabel: string;
  /** Local calendar date YYYY-MM-DD */
  dateISO: string;
  /** split = red/green tracks; together = one shared day */
  mode: "split" | "together";
  blocks: ScheduleBlock[];
};

